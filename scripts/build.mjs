// English: Generate the mirrored static hosting output from canonical root files.
// 中文：以根目录为唯一源码，生成供静态托管使用的 dist 镜像。
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runInNewContext } from 'node:vm';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = join(root, 'dist');
const siteFiles = [
  'index.html', 'project.html', 'styles.css', 'project.css',
  'projects.js', 'project-index.js', 'site-data.js', 'theme.js', 'ui.js', 'script.js', 'detail.js', 'assets'
];

const context = { window: {} };
for (const name of ['projects.js', 'site-data.js']) {
  const path = join(root, name);
  runInNewContext(await readFile(path, 'utf8'), context, { filename: path, timeout: 1000 });
}
// English: Validate references and generate the smaller home-page card index.
// 中文：验证案例引用，并生成较小的首页项目索引。
const { PROJECTS: projects, PORTFOLIO: site } = context.window;
const ids = new Set(projects.map(({ id }) => id));
if (ids.size !== projects.length) throw new Error('Duplicate case study id');
for (const id of [
  ...site.tracks.flatMap(({ projects }) => projects),
  ...site.skills.map(({ project }) => project),
  ...site.experience.flatMap(({ projects }) => projects)
]) {
  if (!ids.has(id)) throw new Error('Unknown case study: ' + id);
}
const index = projects.map(({ id, title, type, categories, summary, keyContribution, built, evidence }) => ({
  id, title, type, categories, summary, keyContribution: keyContribution || built[0],
  evidence: evidence && { label: evidence.label, summary: evidence.summary, links: evidence.links?.slice(0, 1) }
}));
const indexCode = '// English: Generated by scripts/build.mjs from projects.js.\n' +
  '// 中文：由 scripts/build.mjs 从 projects.js 生成。\n' +
  'window.PROJECT_INDEX = ' + JSON.stringify(index, null, 2) + ';\n';
await writeFile(join(root, 'project-index.js'), indexCode);

await rm(output, { recursive: true, force: true });
await mkdir(output);
await Promise.all(siteFiles.map((name) => cp(join(root, name), join(output, name), { recursive: true })));
console.log('Static build ready in dist/');
